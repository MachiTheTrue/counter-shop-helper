-- Typographic punctuation -> plain characters (all fonts can draw these).
local SUBST = {
	["\226\128\148"] = "-", ["\226\128\147"] = "-", ["\226\137\164"] = "<=",
	["\226\137\165"] = ">=", ["\226\134\146"] = "->", ["\226\128\153"] = "'", ["\226\128\152"] = "'",
	["\226\128\156"] = "\"", ["\226\128\157"] = "\"", ["\194\160"] = " ", ["\226\128\175"] = " ",
}
function L.sanitize(s)
	if type(s) ~= "string" or not s:find("[\226]") and not s:find("\194\160") then return s end
	return (s:gsub("\226\128[\147\148\152\153\156\157\175]", SUBST):gsub("\226\137[\164\165]", SUBST)
		:gsub("\226\134\146", SUBST):gsub("\194\160", " "))
end

for _, tbl in pairs(T) do
	for k, v in pairs(tbl) do tbl[k] = L.sanitize(v) end
end

function L.set(lang)
	if T[lang] then L.lang = lang end
end

function L.valid(lang)
	return T[lang] ~= nil
end

-- The whole table of a language (main.lua collects the glyphs a font set needs from it).
function L.strings(lang)
	return T[lang]
end

-- L.t(key, ...) : translated text (English if missing, the key itself as last resort).
function L.t(key, ...)
	local s = T[L.lang][key] or T.en[key] or key
	if select("#", ...) > 0 then
		local ok, out = pcall(string.format, s, ...)
		return ok and out or s
	end
	return s
end

-- Text for an optional key: nil when no language knows it.
function L.maybe(key, ...)
	if T[L.lang][key] == nil and T.en[key] == nil then return nil end
	return L.t(key, ...)
end

-- Native name of a UI language ("fr" -> "Français").
function L.native(lang)
	for _, l in ipairs(L.LANGS) do
		if l[1] == lang then return l[2] end
	end
	return lang
end

return L
